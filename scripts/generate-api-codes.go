//go:build ignore

// Command generate-api-codes 从 internal/dto/code 的 AST 提取具名 Response，
// 生成 web/src/api/codes.ts（只有 code/name，不复制中文文案）。
//
//	go run scripts/generate-api-codes.go          # 写入生成文件
//	go run scripts/generate-api-codes.go -check   # 只校验与现有文件是否一致
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	name string
	code int
}

func main() {
	check := flag.Bool("check", false, "only verify that the generated file is up to date")
	flag.Parse()

	root, err := moduleRoot()
	if err != nil {
		fatal(err)
	}
	srcDir := filepath.Join(root, "internal", "dto", "code")
	outPath := filepath.Join(root, "web", "src", "api", "codes.ts")

	entries, err := extract(srcDir)
	if err != nil {
		fatal(err)
	}
	generated := render(entries)

	if *check {
		existing, readErr := os.ReadFile(outPath)
		if readErr != nil {
			fatal(fmt.Errorf("read generated file: %w", readErr))
		}
		if !bytes.Equal(existing, generated) {
			fatal(fmt.Errorf("%s is out of date; run: go run scripts/generate-api-codes.go", outPath))
		}
		fmt.Printf("%s is up to date (%d codes)\n", outPath, len(entries))
		return
	}

	if err := os.WriteFile(outPath, generated, 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s (%d codes)\n", outPath, len(entries))
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, statErr := os.Stat(filepath.Join(dir, "go.mod")); statErr == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found above %s", dir)
		}
		dir = parent
	}
}

func extract(dir string) ([]entry, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	byCode := make(map[int]string)
	byName := make(map[string]int)
	fset := token.NewFileSet()
	for _, dirEntry := range entries {
		name := dirEntry.Name()
		if dirEntry.IsDir() || filepath.Ext(name) != ".go" || strings.HasSuffix(name, "_test.go") {
			continue
		}
		file, parseErr := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if parseErr != nil {
			return nil, fmt.Errorf("parse %s: %w", name, parseErr)
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.VAR {
				continue
			}
			for _, spec := range gen.Specs {
				value, ok := spec.(*ast.ValueSpec)
				if !ok || len(value.Values) == 0 || len(value.Values) != len(value.Names) {
					continue
				}
				for index, expr := range value.Values {
					switch typed := expr.(type) {
					case *ast.Ident:
						return nil, fmt.Errorf("%s: alias %s = %s is not supported", name, value.Names[index].Name, typed.Name)
					case *ast.CompositeLit:
						if ident, ok := typed.Type.(*ast.Ident); !ok || ident.Name != "Response" {
							continue
						}
						number, found := responseCode(typed)
						if !found {
							return nil, fmt.Errorf("%s: %s must use an integer Code literal", name, value.Names[index].Name)
						}
						varName := value.Names[index].Name
						if previous, exists := byCode[number]; exists {
							return nil, fmt.Errorf("duplicate code %d: %s and %s", number, previous, varName)
						}
						if previous, exists := byName[varName]; exists {
							return nil, fmt.Errorf("duplicate name %s: %d and %d", varName, previous, number)
						}
						byCode[number] = varName
						byName[varName] = number
					}
				}
			}
		}
	}
	if len(byName) == 0 {
		return nil, fmt.Errorf("no Response definitions found in %s", dir)
	}
	result := make([]entry, 0, len(byName))
	for name, code := range byName {
		result = append(result, entry{name: name, code: code})
	}
	sort.Slice(result, func(i, j int) bool {
		if result[i].code != result[j].code {
			return result[i].code < result[j].code
		}
		return result[i].name < result[j].name
	})
	return result, nil
}

func responseCode(lit *ast.CompositeLit) (int, bool) {
	for _, elt := range lit.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := kv.Key.(*ast.Ident)
		if !ok || key.Name != "Code" {
			continue
		}
		value, ok := kv.Value.(*ast.BasicLit)
		if !ok || value.Kind != token.INT {
			return 0, false
		}
		number, err := strconv.Atoi(value.Value)
		if err != nil {
			return 0, false
		}
		return number, true
	}
	return 0, false
}

func render(entries []entry) []byte {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by scripts/generate-api-codes.go; DO NOT EDIT.\n\n")
	buf.WriteString("export const CODES = {\n")
	for _, item := range entries {
		fmt.Fprintf(&buf, "  %s: %d,\n", item.name, item.code)
	}
	buf.WriteString("} as const\n\n")
	buf.WriteString("export type ApiCode = (typeof CODES)[keyof typeof CODES]\n\n")
	buf.WriteString("export const SUCCESS_CODE = CODES.SystemSuccess\n")
	return buf.Bytes()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "generate-api-codes:", err)
	os.Exit(1)
}
